export const GLYPHS: Readonly<Record<string, readonly string[]>> = Object.fromEntries(
  Object.entries(DRAWN).map(([char, rows]) => [char, rows.split('/')]),
)

// What a letter the board has no drawing of is read as.
const LIKE: Readonly<Record<string, string>> = {
  '‘': "'",
  '’': "'",
  '“': '"',
  '”': '"',
  '–': '-',
  '—': '-',
  '×': '✕',
  '•': '·',
}

// A space, and anything the board cannot draw.
const GAP = 2

/** The text as the board can draw it: accents dropped, and curly marks made plain. */
export const plain = (text: string): string =>
  [...text.normalize('NFD').replace(/[̀-ͯ]/g, '')].map(char => LIKE[char] ?? char).join('')

/** Pixels across one letter, without the pixel of air after it. */
export const acrossOf = (char: string): number => GLYPHS[char]?.[0]?.length ?? GAP

/** Pixels across the text as drawn, in the font's own pixels. */
export const widthOf = (text: string): number => {
  const letters = [...plain(text)]

  return letters.reduce((sum, char) => sum + acrossOf(char) + 1, 0) - (letters.length > 0 ? 1 : 0)
}
